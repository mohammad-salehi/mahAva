package com.mahava.app

import com.mahava.app.data.db.DailyLogEntity
import com.mahava.app.data.db.PeriodEventEntity
import com.mahava.app.data.db.ToolRecord
import com.mahava.app.health.TimeRange
import org.junit.Assert.*
import org.junit.Test
import java.time.LocalDate
import java.time.ZoneOffset

class TimeRangeTest {
    private val today = LocalDate.of(2026, 10, 17).toEpochDay()
    private fun log(d: Long, pain: Int? = null, sleep: Int? = null) = DailyLogEntity(epochDay = d, painScore = pain, sleepMinutes = sleep, createdAt = 0, updatedAt = 0)
    private fun period(d: Long) = PeriodEventEntity(startEpochDay = d, endEpochDay = d + 4, createdAt = 0, updatedAt = 0)
    private fun rec(type: String, day: Long?, created: Long = 0, deleted: Long? = null) =
        ToolRecord(id = type + day + created, type = type, epochDay = day, payloadJson = "{}", createdAt = created, updatedAt = created, deletedAt = deleted)

    @Test fun firstEntryIsTheEarliestOfPeriodsLogsAndHerToolRecords() {
        val first = TimeRange.firstEntryDay(
            periods = listOf(period(today - 100), period(today - 70)),
            logs = listOf(log(today - 90), log(today - 3)),
            records = listOf(
                rec("doctor", today - 120),
                rec("insight", today - 500),                 // generated by the app: ignored
                rec("appointments", today - 900, deleted = 1) // deleted: ignored
            ),
            today = today, zone = ZoneOffset.UTC
        )
        assertEquals(today - 120, first)
        val noRecordDay = TimeRange.firstEntryDay(emptyList(), emptyList(),
            listOf(rec("doctor", null, created = LocalDate.ofEpochDay(today - 7).atStartOfDay(ZoneOffset.UTC).toInstant().toEpochMilli())), today, ZoneOffset.UTC)
        assertEquals(today - 7, noRecordDay)
    }

    @Test fun noDataMeansNoFirstEntryAndTheRangeStartsToday() {
        assertNull(TimeRange.firstEntryDay(emptyList(), emptyList(), emptyList(), today))
        assertEquals(today, TimeRange.startFor(TimeRange.ALL, LocalDate.ofEpochDay(today), null, 0))
        assertEquals(today - 400, TimeRange.startFor(TimeRange.ALL, LocalDate.ofEpochDay(today), today - 400, 0))
        assertEquals(LocalDate.ofEpochDay(today).minusMonths(3).toEpochDay(), TimeRange.startFor(3, LocalDate.ofEpochDay(today), today - 400, 0))
    }

    @Test fun granularityFollowsTheSpanAndCoversItExactly() {
        val days = TimeRange.plan(today - 20, today)
        assertEquals(TimeRange.Unit.DAY, days.unit); assertEquals(21, days.size)
        val weeks = TimeRange.plan(today - 120, today)
        assertEquals(TimeRange.Unit.WEEK, weeks.unit)
        assertEquals(today, weeks.buckets.last().end)
        assertEquals(today - 120, weeks.buckets.first().start)
        val months = TimeRange.plan(today - 800, today)
        assertEquals(TimeRange.Unit.MONTH, months.unit)
        assertEquals(1, months.monthsPerBucket)
        assertTrue(months.size in 26..28)
        assertEquals(today - 800, months.buckets.first().start)
        assertEquals(today, months.buckets.last().end)
        // Buckets are contiguous: no day is lost or counted twice.
        months.buckets.zipWithNext().forEach { (a, b) -> assertEquals(a.end + 1, b.start) }
        weeks.buckets.zipWithNext().forEach { (a, b) -> assertEquals(a.end + 1, b.start) }
    }

    @Test fun smallChartsMergeMonthsToStayUnderTheLimit() {
        val p = TimeRange.plan(today - 1100, today, maxPoints = 12)
        assertTrue(p.size <= 12)
        assertTrue(p.monthsPerBucket >= 3)
        assertEquals(today - 1100, p.buckets.first().start); assertEquals(today, p.buckets.last().end)
        assertTrue(TimeRange.plan(today - 60, today, maxPoints = 12).size <= 12)
        assertEquals(TimeRange.Unit.DAY, TimeRange.plan(today - 5, today, maxPoints = 12).unit)
    }

    @Test fun averagesUseOnlyRecordedDays() {
        val plan = TimeRange.plan(today - 13, today)
        val logs = listOf(log(today - 13, pain = 4), log(today - 13, pain = 6), log(today, pain = 2))
        val v = TimeRange.average(logs, plan) { it.painScore?.toFloat() }
        assertEquals(5f, v.first()!!, 0.001f)
        assertNull(v[5])
        assertEquals(2f, v.last()!!, 0.001f)
        val c = TimeRange.countDays(logs, plan) { (it.painScore ?: 0) > 3 }
        assertEquals(2f, c.first()!!, 0.001f); assertNull(c[3])
    }

    @Test fun compressKeepsAllHistoryInFewerPoints() {
        val values = (1..30).map { it.toFloat() }
        val c = TimeRange.compress(values, 12)
        assertTrue(c.size <= 12)
        assertEquals(values.average(), c.average(), 3.0)
        assertEquals(listOf(1f, 2f), TimeRange.compress(listOf(1f, 2f), 12))
    }
}
